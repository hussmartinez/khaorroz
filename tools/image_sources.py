#!/usr/bin/env python3
"""Write docs/image-sources.md: every recipe photo with its Wikimedia Commons link, author and
licence, plus the list of dishes still without a photo (for future photo requests, permission
requests to sources, or the user's own photos).

Run after any photo change:  python3 tools/image_sources.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
C = ROOT / "content"
images = json.loads((C / "images.json").read_text(encoding="utf-8"))["recipes"]
glosses = json.loads((C / "glosses.json").read_text(encoding="utf-8"))

area_of = {}
for area, spec in glosses["areas"].items():
    for cat in spec.get("categories", []):
        for m in cat["members"]:
            area_of[m] = area
recipes = sorted(p.name for p in C.glob("recipe_*.md"))
for r in recipes:
    area_of.setdefault(r, "spain")


def title(f: str) -> str:
    h1 = (C / f).read_text(encoding="utf-8").splitlines()[0][2:]
    return h1.split(" / ")[0].strip()


def slug(f: str) -> str:
    return f[len("recipe_"):-3].replace("_", "-")


AREAS = [("spain", "Spain"), ("sham", "Bilad al-Sham"), ("thai", "Thailand")]
L = ["# Image sources", "",
     "Generated by `tools/image_sources.py` from `content/images.json`; do not edit by hand.",
     "Every photo is from Wikimedia Commons under CC0 / public domain / CC BY / CC BY-SA, credited on the recipe page.", ""]
L.append("| Area | With photo | Total |")
L.append("|---|---|---|")
for a, name in AREAS:
    rs = [r for r in recipes if area_of[r] == a]
    L.append(f"| {name} | {sum(r in images for r in rs)} | {len(rs)} |")
L.append(f"| **All** | **{sum(r in images for r in recipes)}** | **{len(recipes)}** |")

for a, name in AREAS:
    rs = [r for r in recipes if area_of[r] == a]
    L += ["", f"## {name}: photos", "", "| Dish | Page | Photo on Commons | Author | Licence | Note (alt text) |", "|---|---|---|---|---|---|"]
    for r in rs:
        if r not in images:
            continue
        e = images[r]
        alt = re.sub(r"\s+", " ", e.get("alt", {}).get("en", "")).replace("|", "/")
        L.append(f"| {title(r)} | [/recipes/{slug(r)}](https://khaorroz.forfreedom.app/recipes/{slug(r)}) | "
                 f"[{e.get('commonsTitle', 'File')}]({e['source']}) | {e['author'].replace('|', '/')} | "
                 f"[{e['license']}]({e['licenseUrl']}) | {alt} |")
    missing = [r for r in rs if r not in images]
    L += ["", f"## {name}: still without a photo ({len(missing)})", ""]
    L += [f"- {title(r)} ([/recipes/{slug(r)}](https://khaorroz.forfreedom.app/recipes/{slug(r)}))" for r in missing]

out = ROOT / "docs" / "image-sources.md"
out.parent.mkdir(exist_ok=True)
out.write_text("\n".join(L) + "\n", encoding="utf-8")
print(f"wrote {out.relative_to(ROOT)}: {len(images)} photos, {len(recipes) - len(images)} without")
